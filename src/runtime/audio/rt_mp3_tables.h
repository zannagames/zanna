//===----------------------------------------------------------------------===//
// Huffman Tables (ISO 11172-3 Annex B, Table B.7) — the complete Layer III set
//
// Every big_values pair table (1-3, 5-13, 15-31) and both count1 quad tables
// (A / B) are stored as flat binary trees generated from the ISO code tables.
// Node format: value >= 0 is a leaf packing (x, y) as x = value >> 4,
//              y = value & 0xF (quad tables pack v w x y into the low nibble);
//              value < 0 is a branch whose left child is node -value and whose
//              right child is node -value + 1. Node 0 is the root.
// Tables 16-23 share table 16's codes and 24-31 share table 24's codes; only
// their linbits differ (mp3_huff_info). Table 0 is the zero table and tables
// 4 / 14 are reserved by the standard.
//
// Every tree is a complete prefix code (Kraft sum exactly 1) whose leaf set is
// the full (x, y) square of its max value; mp3_huffman_self_check() verifies
// that invariant at test time.
//===----------------------------------------------------------------------===//

/// @brief Huffman table descriptor.
typedef struct {
    int linbits;   // extra bits for values >= 15
    int max_val;   // max x or y before linbits (0 = zero / reserved table)
    int tree_size; // node count of the flat tree that decodes this table
} mp3_huff_table_info_t;

/// @brief Huffman binary tree node.
/// value >= 0: leaf node, x = value >> 4, y = value & 0xF.
/// value < 0: branch, left child at index (-value), right child at (-value + 1).
typedef struct {
    int16_t value; // leaf (>=0) or branch index (<0)
} mp3_huff_node_t;

